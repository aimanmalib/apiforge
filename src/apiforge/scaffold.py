"""Scaffold a complete project from pipeline results."""

from __future__ import annotations
import json
from pathlib import Path
from .generator import CodeGenerator
from .pipeline import PipelineResult


class ProjectScaffold:
    def __init__(self, output_dir: str | Path) -> None:
        self.output_dir = Path(output_dir)
        self.generator = CodeGenerator()

    def scaffold(self, result: PipelineResult) -> dict[str, Path]:
        files: dict[str, Path] = {}
        self.output_dir.mkdir(parents=True, exist_ok=True)
        files["routes"] = self._write("routes.py", result.router_code)
        files["models"] = self._write("models.py", result.model_code)
        files["auth"] = self._write("auth.py", result.auth_code)
        files["tests"] = self._write("tests/test_api.py", result.test_code)
        files["openapi"] = self._write(
            "openapi.json", json.dumps(result.openapi_spec, indent=2)
        )
        files["docs"] = self._write("API.md", result.docs)
        files["main"] = self._write("main.py", self._main(result))
        files["requirements"] = self._write(
            "requirements.txt", self.generator.render("requirements.j2", {})
        )
        files["dockerfile"] = self._write(
            "Dockerfile", self.generator.render("dockerfile.j2", {})
        )
        files["env"] = self._write(
            ".env.example", self.generator.render("env.example.j2", {})
        )
        files["conftest"] = self._write("tests/conftest.py", self._conftest())
        return files

    def _write(self, name: str, content: str) -> Path:
        path = self.output_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        return path

    def _main(self, result: PipelineResult) -> str:
        t = result.description.title
        d = result.description.description
        v = result.description.version
        return (
            '"""' + t + ' -- Auto-generated by APIForge."""\n'
            "from fastapi import FastAPI\nfrom routes import router\n\n"
            'app = FastAPI(title="'
            + t
            + '", description="'
            + d
            + '", version="'
            + v
            + '")\n'
            "app.include_router(router)\n\n"
            "@app.get('/health')\nasync def health():\n    return {'status': 'ok'}\n"
        )

    def _conftest(self) -> str:
        return (
            '"""Test configuration."""\n'
            "import pytest\nfrom fastapi.testclient import TestClient\n\n"
            "@pytest.fixture\ndef client():\n"
            "    from main import app\n    return TestClient(app)\n"
        )
